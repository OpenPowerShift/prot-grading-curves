/**
 * Generate the diagnostic-code reference from the registry.
 *
 * `spec/sections/diagnostics.adoc` is written from
 * `src/constants/diagnostics.ts`, which is where each code's one-line
 * meaning lives -- beside the code, rather than in a document somebody
 * has to remember to update. There was no such reference at all: 76 of
 * the 131 emitted codes appeared nowhere, and four codes the spec named
 * were never raised.
 *
 *   node scripts/sync-diagnostics.mjs          # rewrite the section
 *   node scripts/sync-diagnostics.mjs --check  # fail if it has drifted
 *
 * `--check` is the form for CI: it says the section is stale rather
 * than quietly rewriting a file the run was not asked to touch.
 * `tests/unit/diagnostics.spec.ts` separately holds the registry equal
 * to what the source actually emits, in both directions.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(import.meta.url), '..', '..');
const OUT = join(ROOT, 'spec', 'sections', 'diagnostics.adoc');

/*
 * Read the registry as text rather than importing it: this script runs
 * from plain node with no TypeScript loader, and the shape is regular
 * enough to parse. The test suite imports the module properly and
 * would catch any disagreement between the two readings.
 */
const source = readFileSync(join(ROOT, 'src', 'constants', 'diagnostics.ts'), 'utf8');

const ENTRY = /^ {2}([A-Z][A-Z_0-9]+):\s*\{\s*severity:\s*\[([^\]]*)\],\s*\n?\s*gloss:\s*('|")((?:[^'"\\]|\\.)*)\3,?\s*\},?\s*$/gm;
const SECTION = /^ {2}\/\* ---- (.+?) -+ \*\/$/gm;

/** Section headings, in the order the registry declares them. */
const headings = [];
for (const m of source.matchAll(SECTION)) headings.push({ at: m.index, title: m[1].trim() });

const entries = [];
for (const m of source.matchAll(ENTRY)) {
  entries.push({
    at: m.index,
    code: m[1],
    severity: [...m[2].matchAll(/'(\w+)'/g)].map((s) => s[1]),
    gloss: m[4].replace(/\\'/g, "'").replace(/\\"/g, '"'),
  });
}

if (entries.length < 100) {
  console.error(`only parsed ${entries.length} entries from the registry; refusing to write`);
  process.exit(2);
}

const sectionFor = (at) => {
  let title = 'General';
  for (const h of headings) if (h.at < at) title = h.title;
  return title;
};

const grouped = new Map();
for (const e of entries) {
  const title = sectionFor(e.at);
  if (!grouped.has(title)) grouped.set(title, []);
  grouped.get(title).push(e);
}

const sentence = (s) => s.charAt(0).toUpperCase() + s.slice(1);

const lines = [
  '// Generated by `scripts/sync-diagnostics.mjs` -- do not edit by hand.',
  '// The meaning of each code lives in `src/constants/diagnostics.ts`.',
  '',
  '[[diagnostics]]',
  '== Diagnostic codes',
  '',
  'Every finding the processor can report, with what it means. This',
  'section is generated by `scripts/sync-diagnostics.mjs` from',
  '`src/constants/diagnostics.ts`, and the test suite holds the two',
  'equal to the codes the source actually emits -- in both directions,',
  'so a code cannot be documented without existing and cannot exist',
  'without being documented.',
  '',
  'Severity is as emitted. A handful of codes are raised at more than',
  'one severity depending on which check reaches them first; those list',
  'each, most serious first.',
  '',
  `${entries.length} codes.`,
  '',
];

for (const [title, group] of grouped) {
  lines.push(`=== ${sentence(title)}`, '');
  lines.push('[cols="2,1,4", options="header"]', '|===', '| Code | Severity | Meaning', '');
  for (const e of group.sort((a, b) => a.code.localeCompare(b.code))) {
    lines.push(`| \`${e.code}\` | ${e.severity.join(', ')} | ${e.gloss}`);
  }
  lines.push('|===', '');
}

const rendered = `${lines.join('\n').replace(/\n+$/, '')}\n`;

const check = process.argv.includes('--check');
let before = '';
try { before = readFileSync(OUT, 'utf8'); } catch { /* first run */ }

if (before === rendered) {
  console.log(`diagnostics.adoc is current (${entries.length} codes)`);
  process.exit(0);
}
if (check) {
  console.error('diagnostics.adoc has drifted; run `npm run diagnostics:sync`');
  process.exit(1);
}
writeFileSync(OUT, rendered);
console.log(`wrote diagnostics.adoc (${entries.length} codes)`);
